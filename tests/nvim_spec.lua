vim.opt.rtp:prepend(vim.fn.getcwd())
local helix = require('helix')
local core = require('helix.engine')
local passed, errors = 0, {}
local original_notify = vim.notify
vim.notify = function(msg, level)
  if level == vim.log.levels.ERROR then errors[#errors + 1] = msg end
end
local function eq(a, b) assert(vim.deep_equal(a, b), vim.inspect({actual = a, expected = b})) end
local function text() return table.concat(vim.api.nvim_buf_get_lines(0, 0, -1, false), '\n') end
local function reset(lines, col)
  helix.teardown()
  vim.cmd('enew!')
  vim.api.nvim_buf_set_lines(0, 0, -1, false, lines)
  vim.api.nvim_win_set_cursor(0, {1, col or 0})
  errors = {}
  helix.setup({auto_enable = false})
  assert(helix.enable())
end
local function settle()
  vim.wait(10, function() return false end, 1)
  assert(#errors == 0, table.concat(errors, '\n'))
end
local function keys(input)
  vim.api.nvim_feedkeys(vim.api.nvim_replace_termcodes(input, true, true, true), 'xt', false)
  settle()
end
local function test(name, fn)
  local ok, err = pcall(fn)
  if not ok then error(name .. ': ' .. tostring(err)) end
  passed = passed + 1
  print('ok ' .. passed .. ' - ' .. name)
end

test('mim selects closest pair using actual Neovim input', function()
  reset({'outer([hello])'}, 8); keys('mim')
  eq(helix.get_state().selections, {{start = 7, finish = 12}})
  keys('cworld<Esc>'); eq(text(), 'outer([world])')
end)
test('ma/ selects and deletes a slash object', function()
  reset({'let r = /abc/;'}, 10); keys('ma/d'); eq(text(), 'let r = ;')
end)
test('ma/ finds the closest slash delimiters in paths', function()
  reset({'/usr/local/bin'}, 7); keys('mi/copt<Esc>'); eq(text(), '/usr/opt/bin')
end)
test('rapid insert punctuation cannot enter native command mode', function()
  reset({''}); keys('i:<lt>>é🙂<Esc>'); eq(text(), ':<>é🙂'); eq(vim.fn.mode(), 'n')
end)
test('colon as a textobject is not a command prefix', function()
  reset({':hello:'}, 3); keys('ma:d'); eq(text(), '')
end)
test('mapped normal keys retain their original text in engine insertion', function()
  reset({''})
  vim.keymap.set('n', 'Q', 'gq', {buffer = true})
  keys('iYQ<Esc>')
  eq(text(), 'YQ')
end)
test('multi-key mappings deliver each originally typed character exactly once', function()
  reset({''})
  vim.keymap.set('n', 'jk', '<Esc>', {buffer = true})
  keys('ijk<Esc>')
  eq(text(), 'jk')
end)
test('multicursor insertion undo and redo', function()
  reset({'abc', 'def', 'ghi'}, 1); keys('CCiXY<Esc>'); eq(text(), 'aXYbc\ndXYef\ngXYhi')
  eq(#helix.get_state().selections, 3)
  keys('u'); eq(text(), 'abc\ndef\nghi'); keys('U'); eq(text(), 'aXYbc\ndXYef\ngXYhi')
end)
test('multicursor textobjects and changes', function()
  reset({'/one/', '/two/'}, 2); keys('Cmim')
  -- Slash is explicitly selectable; closest-surround m covers bracket/quote pairs.
  keys('mi/c!<Esc>'); eq(text(), '/!/\n/!/')
end)
test('extmarks render secondary selections and cursors', function()
  reset({'abc', 'def', 'ghi'}); keys('CC')
  local marks = vim.api.nvim_buf_get_extmarks(0, vim.api.nvim_create_namespace('helix.nvim'), 0, -1, {})
  assert(#marks >= 6)
end)
test('repeated word keys advance through a sentence using actual input', function()
  reset({'one two three'})
  for _, expected in ipairs({'one ', 'two ', 'three', 'three'}) do
    keys('w')
    local s = helix.get_state().selections[1]
    eq(text():sub(s.start + 1, s.finish), expected)
  end
end)
test('insert cursor reaches the actual insertion point at line end', function()
  reset({''})
  keys('iX')
  eq(vim.api.nvim_win_get_cursor(0), {1, 1})
  eq(helix.get_state().selections, {{start = 1, finish = 1}})
end)
test('primary insertion cursor does not highlight the next character as a selection', function()
  reset({'abc'})
  keys('iX')
  local marks = vim.api.nvim_buf_get_extmarks(0, vim.api.nvim_create_namespace('helix.nvim'), 0, -1, {details = true})
  for _, mark in ipairs(marks) do
    assert(mark[4].hl_group ~= 'HelixPrimaryCursor', 'duplicate primary insertion cursor')
    for _, chunk in ipairs(mark[4].virt_text or {}) do
      assert(chunk[2] ~= 'HelixPrimaryCursor', 'duplicate primary insertion cursor')
    end
  end
end)
test('end-of-line insertion respects Unicode byte positions and the user cursor shape', function()
  reset({'é🙂'})
  local original = vim.o.guicursor
  vim.o.guicursor = 'a:ver25'
  keys('A界')
  eq(vim.api.nvim_win_get_cursor(0), {1, #'é🙂界'})
  eq(vim.o.guicursor, 'a:ver25')
  helix.disable()
  eq(vim.o.guicursor, 'a:ver25')
  vim.o.guicursor = original
end)
test('virtualedit restores the inherited global setting after disable', function()
  reset({'abc'}); helix.disable()
  local previous_global = vim.go.virtualedit
  local previous_local = vim.api.nvim_get_option_value('virtualedit', {win = 0, scope = 'local'})
  vim.go.virtualedit = 'block'
  vim.api.nvim_set_option_value('virtualedit', '', {win = 0, scope = 'local'})
  helix.enable()
  eq(vim.wo.virtualedit, 'block,onemore')
  helix.disable()
  eq(vim.api.nvim_get_option_value('virtualedit', {win = 0, scope = 'local'}), '')
  eq(vim.wo.virtualedit, 'block')
  vim.go.virtualedit = previous_global
  vim.api.nvim_set_option_value('virtualedit', previous_local, {win = 0, scope = 'local'})
end)
test('pre-existing all virtualedit is preserved', function()
  reset({'abc'}); helix.disable()
  local previous = vim.api.nvim_get_option_value('virtualedit', {win = 0, scope = 'local'})
  vim.wo.virtualedit = 'all'
  helix.enable(); eq(vim.wo.virtualedit, 'all')
  helix.disable(); eq(vim.wo.virtualedit, 'all')
  vim.api.nvim_set_option_value('virtualedit', previous, {win = 0, scope = 'local'})
end)
test('a user option change while enabled is not overwritten on disable', function()
  reset({'abc'}); helix.disable()
  local previous = vim.api.nvim_get_option_value('virtualedit', {win = 0, scope = 'local'})
  helix.enable(); vim.wo.virtualedit = 'all'
  helix.disable(); eq(vim.wo.virtualedit, 'all')
  vim.api.nvim_set_option_value('virtualedit', previous, {win = 0, scope = 'local'})
end)
test('virtualedit is restored when switching to a disabled buffer', function()
  reset({'abc'}); helix.disable()
  local previous = vim.api.nvim_get_option_value('virtualedit', {win = 0, scope = 'local'})
  helix.enable(); vim.cmd('enew!')
  eq(helix.get_state(), nil)
  eq(vim.api.nvim_get_option_value('virtualedit', {win = 0, scope = 'local'}), previous)
end)
test('split windows do not retain inherited temporary cursor options after disable', function()
  reset({'abc'}); helix.disable()
  local first = vim.api.nvim_get_current_win()
  local previous = vim.api.nvim_get_option_value('virtualedit', {win = first, scope = 'local'})
  helix.enable(); vim.cmd.vsplit()
  local second = vim.api.nvim_get_current_win()
  helix.disable()
  eq(vim.api.nvim_get_option_value('virtualedit', {win = first, scope = 'local'}), previous)
  eq(vim.api.nvim_get_option_value('virtualedit', {win = second, scope = 'local'}), previous)
  vim.cmd('only!')
end)
test('temporary cursor options do not leak into inactive floating windows', function()
  reset({'abc'}); helix.disable()
  local previous = vim.api.nvim_get_option_value('virtualedit', {win = 0, scope = 'local'})
  helix.enable()
  local buf = vim.api.nvim_create_buf(false, true)
  local win = vim.api.nvim_open_win(buf, false, {relative = 'editor', row = 1, col = 1, width = 10, height = 2})
  eq(vim.api.nvim_get_option_value('virtualedit', {win = win, scope = 'local'}), previous)
  vim.api.nvim_win_close(win, true)
end)
test('teardown restores the original window cursor options', function()
  reset({'abc'}); helix.disable()
  local previous = vim.api.nvim_get_option_value('virtualedit', {win = 0, scope = 'local'})
  helix.enable(); keys('A!')
  helix.teardown()
  eq(vim.api.nvim_get_option_value('virtualedit', {win = 0, scope = 'local'}), previous)
end)
test('regex matching and anchored split use original-string offsets', function()
  reset({'cat dog cat'}); keys('%'); assert(helix.select_regex('cat'))
  eq(#helix.get_state().selections, 2); keys('cx<Esc>'); eq(text(), 'x dog x')
  reset({'abc'}); keys('%'); helix.select_regex('^', nil, true)
  eq(#helix.get_state().selections, 1)
  eq(helix.get_state().selections[1].finish, 3)
end)
test('selection regex prompt invokes the UI callback', function()
  reset({'cat dog cat'}); keys('%')
  local original = vim.ui.input
  vim.ui.input = function(_, callback) callback('cat') end
  keys('s'); vim.ui.input = original
  eq(#helix.get_state().selections, 2)
end)
