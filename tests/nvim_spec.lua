vim.opt.rtp:prepend(vim.fn.getcwd())
local helix = require('helix')
local core = require('helix.engine')
local passed, errors = 0, {}
local original_notify = vim.notify
vim.notify = function(msg, level)
  if level == vim.log.levels.ERROR then errors[#errors + 1] = msg end
end
local function eq(a, b) assert(vim.deep_equal(a, b), vim.inspect({actual = a, expected = b})) end
local function text() return table.concat(vim.api.nvim_buf_get_lines(0, 0, -1, false), '\n') end
local function reset(lines, col)
  helix.teardown()
  vim.cmd('enew!')
  vim.api.nvim_buf_set_lines(0, 0, -1, false, lines)
  vim.api.nvim_win_set_cursor(0, {1, col or 0})
  errors = {}
  helix.setup({auto_enable = false})
  assert(helix.enable())
end
local function settle()
  vim.wait(10, function() return false end, 1)
  assert(#errors == 0, table.concat(errors, '\n'))
end
local function keys(input)
  vim.api.nvim_feedkeys(vim.api.nvim_replace_termcodes(input, true, false, true), 'xt', false)
  settle()
end
local function test(name, fn)
  local ok, err = pcall(fn)
  if not ok then error(name .. ': ' .. tostring(err)) end
  passed = passed + 1
  print('ok ' .. passed .. ' - ' .. name)
end

test('mim selects closest pair using actual Neovim input', function()
  reset({'outer([hello])'}, 8); keys('mim')
  eq(helix.get_state().selections, {{start = 7, finish = 12}})
  keys('cworld<Esc>'); eq(text(), 'outer([world])')
end)
test('ma/ selects and deletes a slash object', function()
  reset({'let r = /abc/;'}, 10); keys('ma/d'); eq(text(), 'let r = ;')
end)
test('ma/ finds the closest slash delimiters in paths', function()
  reset({'/usr/local/bin'}, 7); keys('mi/copt<Esc>'); eq(text(), '/usr/opt/bin')
end)
test('rapid insert punctuation cannot enter native command mode', function()
  reset({''}); keys('i:<lt>>é🙂<Esc>'); eq(text(), ':<>é🙂'); eq(vim.fn.mode(), 'n')
end)
test('colon as a textobject is not a command prefix', function()
  reset({':hello:'}, 3); keys('ma:d'); eq(text(), '')
end)
test('multicursor insertion undo and redo', function()
  reset({'abc', 'def', 'ghi'}, 1); keys('CCiXY<Esc>'); eq(text(), 'aXYbc\ndXYef\ngXYhi')
  eq(#helix.get_state().selections, 3)
  keys('u'); eq(text(), 'abc\ndef\nghi'); keys('U'); eq(text(), 'aXYbc\ndXYef\ngXYhi')
end)
test('multicursor textobjects and changes', function()
  reset({'/one/', '/two/'}, 2); keys('Cmim')
  -- Slash is explicitly selectable; closest-surround m covers bracket/quote pairs.
  keys('mi/c!<Esc>'); eq(text(), '/!/\n/!/')
end)
test('extmarks render secondary selections and cursors', function()
  reset({'abc', 'def', 'ghi'}); keys('CC')
  local marks = vim.api.nvim_buf_get_extmarks(0, vim.api.nvim_create_namespace('helix.nvim'), 0, -1, {})
  assert(#marks >= 6)
end)
test('regex matching and anchored split use original-string offsets', function()
  reset({'cat dog cat'}); keys('%'); assert(helix.select_regex('cat'))
  eq(#helix.get_state().selections, 2); keys('cx<Esc>'); eq(text(), 'x dog x')
  reset({'abc'}); keys('%'); helix.select_regex('^', nil, true)
  eq(#helix.get_state().selections, 1)
  eq(helix.get_state().selections[1].finish, 3)
end)
test('selection regex prompt invokes the UI callback', function()
  reset({'cat dog cat'}); keys('%')
  local original = vim.ui.input
  vim.ui.input = function(_, callback) callback('cat') end
  keys('s'); vim.ui.input = original
  eq(#helix.get_state().selections, 2)
end)
test('multiline Unicode paste distributes to all insertion points', function()
  reset({'a', 'b'}); keys('Ci'); vim.api.nvim_paste('é🙂\n', true, -1); keys('<Esc>')
  eq(text(), 'é🙂\na\né🙂\nb')
end)
test('streaming paste stays in one engine undo session', function()
  reset({'abc'}); keys('i'); vim.api.nvim_paste('X', false, 1); vim.api.nvim_paste('Y', false, 3)
  keys('<Esc>'); eq(text(), 'XYabc'); keys('u'); eq(text(), 'abc')
end)
test('Unicode replacements preserve shared-byte prefixes', function()
  reset({'á'}); keys('râ'); eq(text(), 'â')
  reset({'aé🙂z'}, 1); keys('lr界'); eq(text(), 'aé界z')
end)
test('insert End and Home are insertion boundaries', function()
  reset({'abc'}); keys('i<End>X<Home>Y<Esc>'); eq(text(), 'YabcX')
end)
test('control-H backspaces at all cursors', function()
  reset({'abc', 'def'}, 1); keys('CiX<C-h><Esc>'); eq(text(), 'abc\ndef')
end)
test('native command-line write flushes all pending engine edits', function()
  reset({'abc'}); local filename = vim.fn.tempname()
  keys('iX<Esc>:write! ' .. vim.fn.fnameescape(filename) .. '<CR>')
  eq(vim.fn.readfile(filename), {'Xabc'}); vim.fn.delete(filename)
end)
test('external edits reset engine undo rather than overwriting external text', function()
  reset({'abc'}); keys('d'); vim.api.nvim_buf_set_lines(0, 0, -1, false, {'external'})
  keys('u'); eq(text(), 'external')
end)
test('disable returns native Vim input and clears decorations', function()
  reset({'abc'}); helix.disable(); eq(helix.get_state(), nil); keys('0x'); eq(text(), 'bc')
  eq(vim.api.nvim_buf_get_extmarks(0, vim.api.nvim_create_namespace('helix.nvim'), 0, -1, {}), {})
end)
test('enable and teardown do not add any editing keymaps', function()
  reset({'abc'}); eq(vim.api.nvim_buf_get_keymap(0, 'n'), {}); helix.teardown()
  eq(vim.fn.exists(':HelixEnable'), 0)
end)
test('read-only and special buffers are excluded', function()
  reset({'abc'}); helix.disable(); vim.bo.readonly = true; eq(helix.enable(), false); vim.bo.readonly = false
  vim.bo.buftype = 'nofile'; eq(helix.enable(), false); vim.bo.buftype = ''
end)
test('counted textobjects and escaped slash delimiter', function()
  reset({'outer([hello])'}, 8); keys('2mim'); local state = helix.get_state()
  eq(state.text:sub(state.selections[1].start + 1, state.selections[1].finish), '[hello]')
  reset({'/a\\/b/'}, 2); keys('mi/cx<Esc>'); eq(text(), '/x/')
end)
test('native window switching preserves distinct buffer states', function()
  reset({'abc'}); keys('iX<Esc>'); local first = vim.api.nvim_get_current_buf()
  keys('<C-w>v'); vim.cmd('enew!'); vim.api.nvim_buf_set_lines(0, 0, -1, false, {'def'}); helix.enable()
  keys('d'); eq(text(), 'ef'); vim.cmd('buffer ' .. first); settle(); eq(text(), 'Xabc')
  vim.cmd('only!')
end)
test('new lines can be inserted above and below all cursors', function()
  reset({'abc', 'def'}); keys('CoX<Esc>'); eq(text(), 'abc\nX\ndef\nX')
end)
test('no-op insert leaves the redo branch intact', function()
  reset({'abc'}); keys('dui<Esc>U'); eq(text(), 'bc')
end)
test('mouse or external cursor movement resynchronizes the selection', function()
  reset({'abc'}); vim.api.nvim_win_set_cursor(0, {1, 2}); vim.api.nvim_exec_autocmds('CursorMoved', {buffer = 0})
  keys('rX'); eq(text(), 'abX')
end)
helix.teardown()
vim.notify = original_notify
print(passed .. ' real Neovim integration tests passed')
vim.cmd('qa!')
