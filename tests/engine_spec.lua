package.path = './lua/?.lua;./lua/?/init.lua;' .. package.path
local core = require('helix.engine')
local valid_utf8 = dofile('tests/support.lua').valid_utf8
local passed = 0
local function eq(a, b) assert(a == b, string.format('expected %q, got %q', tostring(b), tostring(a))) end
local function test(name, fn)
  local ok, err = pcall(fn)
  if not ok then error(name .. ': ' .. tostring(err)) end
  passed = passed + 1; print('ok ' .. passed .. ' - ' .. name)
end
local function feed(e, ...)
  for _, key in ipairs({...}) do e:input(key); e:validate() end
end
local function selected(e, i)
  local s = e.selections[i or e.primary]
  return e.text:sub(s.start + 1, s.finish)
end
local function literal(pattern)
  return function(value, offset)
    local a, b = value:find(pattern, offset + 1, true)
    if a then return a - 1, b end
  end
end

