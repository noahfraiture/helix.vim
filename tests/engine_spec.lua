-- Property checks exercise Unicode and range invariants across random command streams.
test('deterministic random editing preserves all range invariants', function()
  local seed = 73
  local function random(n) seed = (seed * 48271) % 2147483647; return seed % n + 1 end
  local keys = {'h','j','k','l','w','b','e','v','C','i','a','c','d','y','p','P','u','U',
    'x','r','m','s','(',')','/','%',';',',','<Esc>','<BS>','<CR>','é','🙂','X'}
  for _ = 1, 30 do
    local e = core.new('(aé🙂) /bc/\nxy\nz')
    for _ = 1, 200 do
      if #e.text > 2000 then e = core.new('reset\ntext') end
      feed(e, keys[random(#keys)])
      assert(valid_utf8(e.text), 'invalid UTF-8 text')
    end
  end
end)
